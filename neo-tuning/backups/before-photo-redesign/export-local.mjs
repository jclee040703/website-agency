import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=path.dirname(fileURLToPath(import.meta.url));
const dist=path.join(root,'dist');
let html=fs.readFileSync(path.join(dist,'index.html'),'utf8');
const css=fs.readFileSync(path.join(dist,'style.css'),'utf8').replace(/^@import[^;]+;\s*/,'');
const js=fs.readFileSync(path.join(dist,'app.js'),'utf8');
html=html.replace(/\s*<link rel="preload"[^>]+>/,'');
html=html.replace('<link rel="stylesheet" href="style.css">','<style>'+css+'</style>');
html=html.replace('<script src="app.js" defer></script>','');
html=html.replace('</body>','<script>'+js+'</script></body>');
html=html.replace(/src="assets\/([^"]+)"/g,(_,name)=>'src="data:image/jpeg;base64,'+fs.readFileSync(path.join(dist,'assets',name)).toString('base64')+'"');
const output=path.join(root,'NEO TUNING.html');
fs.writeFileSync(output,html,'utf8');
console.log('Offline preview: '+output);
